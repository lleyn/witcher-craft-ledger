export function nameRu(name: string): string {
  return NAME_RU[name] ?? SUBSTANCE_RU[name] ?? name;
}

export function timeRu(value: string): string {
  if (value === "g Hours") return "9 ч";
  if (value === "1/2 Hour") return "30 мин";
  const match = value.match(/^(\d+) (Minute|Minutes|Round|Rounds|Hour|Hours)$/);
  if (!match) return value;
  const [, amount, unit] = match;
  if (unit.startsWith("Minute")) return `${amount} мин`;
  if (unit.startsWith("Round")) return `${amount} раундов`;
  return `${amount} ч`;
}

export function formulaCostRu(value: number | string): string {
  return value === "N/A" ? "Нет в продаже" : String(value);
}

export function warningRu(value: string): string {
  const prefixes = ["Циклическая зависимость: ", "Нет цены для субстанции ", "Нет цены для компонента "];
  const prefix = prefixes.find((item) => value.startsWith(item));
  return prefix ? `${prefix}${nameRu(value.slice(prefix.length))}` : value;
}
